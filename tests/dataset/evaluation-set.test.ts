/**
 * Contract tests over the evaluation set in `submission_package/02_tests_and_outputs/dataset`.
 *
 * The eight assignment categories are covered by the unit suites in `tests/grading`. These
 * tests cover the layer between those units and a live grading run: that the real answer
 * scripts we ship actually feed the pipeline what it needs. They make no model calls, so
 * they stay deterministic and run in the normal suite.
 *
 * What would otherwise only surface as a bad grade at run time:
 *   - a script rendered without a text layer would be graded as a confident zero
 *   - a quote that cannot be located would silently lose its highlight
 *   - a ground truth file that disagrees with the paper's own maximum would make every
 *     agreement number in outputs/ meaningless
 */
import { describe, it, expect, beforeAll } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { extractTextWithPositions } from '@/lib/pdf/extract';
import { findEvidence } from '@/lib/pdf/coordinates';
import { validateGradingResult } from '@/lib/grading/validate';
import { calculateTotal } from '@/lib/grading/scoring';
import { determineReviewNeeded } from '@/lib/grading/confidence';
import { ExtractedPageText } from '@/types/pdf';
import { RubricResultInput } from '@/types/grading';

const DATASET = path.resolve('submission_package/02_tests_and_outputs/dataset');
const MANIFEST = path.join(DATASET, 'manifest.json');

interface ScriptMeta {
  id: string;
  split: 'train' | 'test';
  file: string;
  name: string;
  roll: string;
  profile: string;
  expected: { q1: number; q2: number; q3: number; total: number };
  tests: string;
}

const available = fs.existsSync(MANIFEST);
const manifest: { scripts: ScriptMeta[] } = available
  ? JSON.parse(fs.readFileSync(MANIFEST, 'utf-8'))
  : { scripts: [] };

const pathOf = (m: ScriptMeta) => path.join(DATASET, m.split, m.file);
const find = (id: string) => manifest.scripts.find((m) => m.id === id)!;

// Generated by tools/make-student-scripts.mjs. Skip rather than fail when a checkout has
// not built the dataset yet — the unit suites still cover the pipeline itself.
const suite = available ? describe : describe.skip;

suite('evaluation set — every script is gradable', () => {
  const extracted = new Map<string, { fullText: string; pages: ExtractedPageText[] }>();

  beforeAll(async () => {
    for (const meta of manifest.scripts) {
      extracted.set(meta.id, await extractTextWithPositions(pathOf(meta)));
    }
  }, 60_000);

  it('ships the twelve scripts named in the manifest', () => {
    expect(manifest.scripts).toHaveLength(12);
    expect(manifest.scripts.filter((m) => m.split === 'train')).toHaveLength(5);
    expect(manifest.scripts.filter((m) => m.split === 'test')).toHaveLength(7);
    for (const meta of manifest.scripts) {
      expect(fs.existsSync(pathOf(meta)), `${meta.id} missing at ${pathOf(meta)}`).toBe(true);
    }
  });

  it('gives every script a real text layer with positioned items', () => {
    // A PDF with pixels but no text layer is rejected by the pipeline as NO_TEXT_LAYER.
    // If a script ever rendered that way it would be graded as a legitimate zero.
    for (const meta of manifest.scripts) {
      const { pages } = extracted.get(meta.id)!;
      const items = pages.flatMap((p) => p.items);
      // TR-04 is deliberately near-empty; it still needs a text layer, just a short one.
      const floor = meta.id === 'TR-04' ? 5 : 20;
      expect(items.length, `${meta.id} has no positioned text items`).toBeGreaterThan(floor);
      expect(pages.every((p) => p.width > 0 && p.height > 0)).toBe(true);
    }
  });

  it('keeps the blank script blank — no answer text for the grader to credit', () => {
    const { pages } = extracted.get('TR-04')!;
    const body = pages
      .map((p) => p.text)
      .join(' ')
      .replace(/GradeSense — Student Answer Script|Roll No\.|Page \d+|Sana Qureshi|S-1071/g, '');
    // Headings and one "Not attempted" line only.
    expect(body.length).toBeLessThan(400);
    expect(body).toMatch(/Not attempted/i);
  });

  it('carries the diagram labels into the text layer', () => {
    // The diagrams are vector strokes; only their labels are extractable. A rubric point
    // about instrument placement can only be evidenced if those labels survive.
    const clean = extracted.get('TE-05')!.fullText;
    expect(clean).toMatch(/Voltmeter \(parallel across bulb\)/);
    expect(clean).toMatch(/Ammeter \(in series\)/);
    const wrong = extracted.get('TR-03')!.fullText;
    expect(wrong).toMatch(/Voltmeter \(in series with bulb\)/);
  });
});

suite('evaluation set — evidence can be located on the page', () => {
  const pagesOf = async (id: string) => {
    const { pages } = await extractTextWithPositions(pathOf(find(id)));
    return pages.map((p) => ({ pageNumber: p.pageNumber, items: p.items }));
  };

  it('locates a verbatim quote from the full-credit script', async () => {
    const pages = await pagesOf('TR-01');
    const located = findEvidence(
      'The voltmeter is connected in parallel across the bulb',
      pages
    );

    expect(located).not.toBeNull();
    expect(located!.page).toBe(1);
    expect(located!.bbox.width).toBeGreaterThan(0);
    expect(located!.rects.length).toBeGreaterThan(0);
    // Every per-line rect must sit inside the union box, or the exported PDF and the
    // on-screen overlay disagree about where the highlight is.
    for (const r of located!.rects) {
      expect(r.x).toBeGreaterThanOrEqual(located!.bbox.x - 1);
      expect(r.y).toBeGreaterThanOrEqual(located!.bbox.y - 1);
    }
  }, 30_000);

  it('still locates the quote through scan noise', async () => {
    // TR-05 says "conected in paralel across the bufb". A model quoting the sentence in
    // clean spelling must still land on the right words.
    const pages = await pagesOf('TR-05');
    const located = findEvidence('The voltrneter is conected in paralel across the bufb', pages);

    expect(located).not.toBeNull();
    expect(located!.page).toBe(1);
  }, 30_000);

  it('draws no box when the quote is not on the page', async () => {
    const pages = await pagesOf('TR-04');
    expect(
      findEvidence('The ammeter must be connected in series with the bulb', pages)
    ).toBeNull();
  }, 30_000);

  it('finds the wrong-equilibrium sentence that costs TE-06 its marks', async () => {
    const pages = await pagesOf('TE-06');
    const located = findEvidence(
      'the equilibrium is at a price of Rs 40 and a quantity of 40 units',
      pages
    );

    expect(located).not.toBeNull();
    expect(located!.page).toBeGreaterThanOrEqual(2);
  }, 30_000);
});

suite('evaluation set — the ground truth is internally consistent', () => {
  it('never expects more than a question or the paper allows', () => {
    for (const m of manifest.scripts) {
      for (const q of [m.expected.q1, m.expected.q2, m.expected.q3]) {
        expect(q, `${m.id} expects more than 5 on a question`).toBeLessThanOrEqual(5);
        expect(q).toBeGreaterThanOrEqual(0);
      }
      const sum = m.expected.q1 + m.expected.q2 + m.expected.q3;
      expect(sum, `${m.id} per-question marks do not sum to its total`).toBeCloseTo(
        m.expected.total,
        5
      );
      expect(m.expected.total).toBeLessThanOrEqual(15);
    }
  });

  it('spans the full range of outcomes a marker has to handle', () => {
    const totals = manifest.scripts.map((m) => m.expected.total);
    expect(Math.min(...totals)).toBe(0); // a blank script
    expect(Math.max(...totals)).toBe(15); // a full-credit script
    // and something in between, or the set proves nothing about partial credit
    expect(totals.filter((t) => t > 0 && t < 15).length).toBeGreaterThanOrEqual(8);
  });

  it('matches ground_truth.csv row for row', () => {
    const csv = fs
      .readFileSync(path.join(DATASET, 'ground_truth.csv'), 'utf-8')
      .trim()
      .split('\n');
    expect(csv).toHaveLength(manifest.scripts.length + 1);

    for (const [i, meta] of manifest.scripts.entries()) {
      const cells = csv[i + 1].split(',');
      expect(cells[0]).toBe(meta.id);
      expect(Number(cells[8])).toBeCloseTo(meta.expected.total, 5);
    }
  });
});

/**
 * The firewall, exercised at this paper's real shape (3 questions × 5 rubric points of
 * 1 mark). The unit suite proves the rules; this proves they hold for the paper we ship.
 */
describe('evaluation set — the scoring firewall holds for a 15-mark paper', () => {
  const points = Array.from({ length: 15 }, (_, i) => ({ id: `rp-${i + 1}`, maxMarks: 1 }));

  const resultsFor = (marks: number[]): RubricResultInput[] =>
    marks.map((m, i) => ({
      rubricId: `rp-${i + 1}`,
      status: m === 1 ? 'CORRECT' : m === 0 ? 'MISSING' : 'PARTIAL',
      marksAwarded: m,
      feedback: 'f',
      correction: null,
      confidence: 0.9,
      humanReview: false,
      evidence: { text: 'e', page: 1 },
    })) as RubricResultInput[];

  it('accepts a full-credit run and totals it in code', () => {
    const results = resultsFor(Array(15).fill(1));
    const { total, maxMarks } = validateGradingResult({ rubricResults: results } as any, points);

    expect(maxMarks).toBe(15);
    expect(total).toBe(15);
    expect(calculateTotal(results)).toBe(total);
  });

  it('rejects a single rubric point awarded above its maximum', () => {
    const results = resultsFor([...Array(14).fill(1), 2]);
    expect(() => validateGradingResult({ rubricResults: results } as any, points)).toThrow(
      /INVALID_MARKS/
    );
  });

  it('rejects a rubric id that is not part of this paper', () => {
    const results = resultsFor(Array(15).fill(1));
    results[3].rubricId = 'rp-from-another-paper';
    expect(() => validateGradingResult({ rubricResults: results } as any, points)).toThrow(
      /UNKNOWN_RUBRIC_ID/
    );
  });

  it('sends every partial mark to a human', () => {
    // TR-02 and TE-03 are built to land on partial credit, so this is the review path
    // the majority of real scripts take.
    const [partial] = resultsFor([0.5]);
    expect(determineReviewNeeded(partial)).toBe(true);
  });

  it('sends a point with no evidence to a human even when the model is confident', () => {
    const [noEvidence] = resultsFor([1]);
    noEvidence.evidence = null;
    expect(determineReviewNeeded(noEvidence)).toBe(true);
  });
});
